/* =========================================================
   14. CHAT MESSAGE BUILDER
========================================================= */

function buildChatMessages(options = {}) {

    const systemPrompt = buildSystemPrompt({
        mode: options.mode || "normal",
        context: options.context || ""
    });

    const history = Array.isArray(options.history)
        ? options.history
        : [];

    const messages = [
        {
            role: "system",
            content: systemPrompt
        }
    ];

    const recentHistory = history.slice(
        -CHAT.MAX_CONTEXT_MESSAGES
    );

    for (const item of recentHistory) {

        if (!item || typeof item !== "object") {
            continue;
        }

        const role = item.role;

        if (!["user", "assistant"].includes(role)) {
            continue;
        }

        const content = sanitizeText(
            item.content,
            CHAT.MAX_MESSAGE_LENGTH
        );

        if (!content) {
            continue;
        }

        messages.push({
            role,
            content
        });
    }

    const currentMessage = sanitizeText(
        options.message || "",
        CHAT.MAX_MESSAGE_LENGTH
    );

    if (currentMessage) {

        messages.push({
            role: "user",
            content: currentMessage
        });

    }

    return messages;

}


