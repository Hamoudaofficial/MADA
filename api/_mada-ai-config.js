/* =========================================================
   17. TEXT VALIDATION
========================================================= */

function sanitizeText(value, maxLength = 4000) {

    if (typeof value !== "string") {
        return "";
    }

    return value
        .replace(/\u0000/g, "")
        .trim()
        .slice(0, maxLength);

}


function validateMessage(message) {

    if (typeof message !== "string") {

        return {
            valid: false,
            error: "INVALID_MESSAGE_TYPE"
        };

    }

    const cleanMessage = sanitizeText(
        message,
        CHAT.MAX_MESSAGE_LENGTH
    );

    if (!cleanMessage) {

        return {
            valid: false,
            error: "EMPTY_MESSAGE"
        };

    }

    if (message.length > CHAT.MAX_MESSAGE_LENGTH) {

        return {
            valid: false,
            error: "MESSAGE_TOO_LONG"
        };

    }

    return {
        valid: true,
        message: cleanMessage
    };

}


